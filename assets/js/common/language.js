function getT(key) {
    const lang = localStorage.getItem('selectedLanguage') || 'tr';
    return translations[lang][key] || key;
}

let typedInstance = null;

function changeLanguage(lang) {
    localStorage.setItem('selectedLanguage', lang);
    document.documentElement.lang = lang;

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');

        if (translations[lang] && translations[lang][key]) {
            const translation = translations[lang][key];

            if (element.classList.contains('typed')) {
                element.setAttribute('data-typed-items', translation);
                restartTypedJS(element, translation);
            }
            else if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translation;
            }
            else {
                element.innerHTML = translation;
            }
        }
    });

    const langMenuText = document.querySelector('.dropdown > a > span');
    if (langMenuText) {
        langMenuText.innerHTML = lang === 'tr' ? "🌍 Dil / Language" : (lang === 'en' ? "🌍 Language" : "🌍 Sprache");
    }

    if (document.getElementById('vinChart') && document.getElementById('vinChart').chart) {
        hesapla();
    }

    if (typeof toggleRectifierType === "function") {
        toggleRectifierType();
    }
}

function restartTypedJS(element, newStrings) {
    if (typedInstance !== null) {
        typedInstance.destroy();
    }

    const typed_strings = newStrings.split(',').map(item => item.trim());

    typedInstance = new Typed(element, {
        strings: typed_strings,
        loop: true,
        typeSpeed: 100,
        backSpeed: 50,
        backDelay: 2000
    });
}

(function () {
    const savedLanguage = localStorage.getItem('selectedLanguage') || 'en';

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', () => changeLanguage(savedLanguage));
    } else {
        changeLanguage(savedLanguage);
    }
})();
